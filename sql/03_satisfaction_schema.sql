CREATE TABLE satisfaction_survey (
 survey_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 program_id NUMBER(19) NOT NULL REFERENCES program(program_id),
 survey_name VARCHAR2(150 CHAR) NOT NULL,
 start_date DATE NOT NULL,
 end_date DATE NOT NULL,
 survey_status VARCHAR2(10 CHAR) DEFAULT 'DRAFT' NOT NULL
   CHECK(survey_status IN ('DRAFT','OPEN','CLOSED')),
 created_by NUMBER(19) NOT NULL REFERENCES user_account(user_id),
 created_at TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
 CONSTRAINT ck_survey_dates CHECK(end_date >= start_date),
 CONSTRAINT uq_survey_program_name UNIQUE(program_id,survey_name)
);

CREATE TABLE survey_question (
 question_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 survey_id NUMBER NOT NULL REFERENCES satisfaction_survey(survey_id),
 question_order NUMBER(4) NOT NULL CHECK(question_order > 0),
 question_text VARCHAR2(500 CHAR) NOT NULL,
 question_type VARCHAR2(10 CHAR) NOT NULL CHECK(question_type IN ('SCORE','TEXT')),
 is_required CHAR(1) DEFAULT 'Y' NOT NULL CHECK(is_required IN ('Y','N')),
 is_active CHAR(1) DEFAULT 'Y' NOT NULL CHECK(is_active IN ('Y','N')),
 CONSTRAINT uq_survey_question_order UNIQUE(survey_id,question_order),
 CONSTRAINT uq_survey_question_pair UNIQUE(survey_id,question_id)
);

CREATE TABLE survey_response (
 response_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 survey_id NUMBER NOT NULL REFERENCES satisfaction_survey(survey_id),
 student_id NUMBER(19) NOT NULL REFERENCES student(student_id),
 response_status VARCHAR2(15 CHAR) DEFAULT 'IN_PROGRESS' NOT NULL
   CHECK(response_status IN ('IN_PROGRESS','COMPLETED')),
 started_at TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
 completed_at TIMESTAMP,
 CONSTRAINT uq_survey_response_student UNIQUE(survey_id,student_id),
 CONSTRAINT uq_survey_response_pair UNIQUE(survey_id,response_id),
 CONSTRAINT ck_survey_response_completion CHECK(
   (response_status='IN_PROGRESS' AND completed_at IS NULL) OR
   (response_status='COMPLETED' AND completed_at IS NOT NULL))
);

CREATE TABLE survey_response_detail (
 detail_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 response_id NUMBER NOT NULL,
 survey_id NUMBER NOT NULL,
 question_id NUMBER NOT NULL,
 score NUMBER(1),
 answer_text VARCHAR2(2000 CHAR),
 answered_at TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
 CONSTRAINT fk_survey_detail_response FOREIGN KEY(survey_id,response_id)
   REFERENCES survey_response(survey_id,response_id),
 CONSTRAINT fk_survey_detail_question FOREIGN KEY(survey_id,question_id)
   REFERENCES survey_question(survey_id,question_id),
 CONSTRAINT uq_survey_detail_question UNIQUE(response_id,question_id),
 CONSTRAINT ck_survey_detail_value CHECK(
   (score BETWEEN 1 AND 5 AND answer_text IS NULL) OR
   (score IS NULL AND answer_text IS NOT NULL AND LENGTH(TRIM(answer_text)) > 0))
);

CREATE INDEX ix_survey_program_status ON satisfaction_survey(program_id,survey_status);
CREATE INDEX ix_survey_question_survey ON survey_question(survey_id,is_active,question_order);
CREATE INDEX ix_survey_response_survey ON survey_response(survey_id,response_status,student_id);
CREATE INDEX ix_survey_detail_question ON survey_response_detail(question_id,response_id);

COMMENT ON TABLE satisfaction_survey IS '프로그램 만족도 조사 기본정보';
COMMENT ON TABLE survey_question IS '조사별 점수형·주관식 문항';
COMMENT ON TABLE survey_response IS '학생별 조사 응답 및 완료 상태';
COMMENT ON TABLE survey_response_detail IS '문항별 만족도 점수 또는 주관식 의견';

CREATE OR REPLACE VIEW v_satisfaction_summary AS
SELECT s.survey_id,s.survey_name,p.program_id,p.detail_program_name,
 q.question_id,q.question_order,q.question_text,q.question_type,
 ROUND(AVG(CASE WHEN q.question_type='SCORE' AND r.response_status='COMPLETED' THEN d.score END),2) average_score,
 COUNT(CASE WHEN r.response_status='COMPLETED' THEN d.detail_id END) response_count
FROM satisfaction_survey s
JOIN program p ON p.program_id=s.program_id
JOIN survey_question q ON q.survey_id=s.survey_id AND q.is_active='Y'
LEFT JOIN survey_response_detail d ON d.survey_id=s.survey_id AND d.question_id=q.question_id
LEFT JOIN survey_response r ON r.response_id=d.response_id AND r.response_status='COMPLETED'
GROUP BY s.survey_id,s.survey_name,p.program_id,p.detail_program_name,
 q.question_id,q.question_order,q.question_text,q.question_type;

-- 점수형은 학과·학년 집계, 주관식은 익명 의견 단위 행으로 제공한다.
-- 학생 이름·학번·응답 ID는 결과에 노출하지 않는다.
CREATE OR REPLACE VIEW v_satisfaction_by_department AS
SELECT s.survey_id,s.survey_name,p.program_id,p.detail_program_name,
 q.question_id,q.question_order,q.question_text,q.question_type,
 dpt.department_id,dpt.department_name,st.grade,
 ROUND(AVG(d.score),2) average_score,COUNT(*) response_count,
 CAST(NULL AS VARCHAR2(2000 CHAR)) answer_text
FROM satisfaction_survey s
JOIN program p ON p.program_id=s.program_id
JOIN survey_question q ON q.survey_id=s.survey_id AND q.is_active='Y' AND q.question_type='SCORE'
JOIN survey_response r ON r.survey_id=s.survey_id AND r.response_status='COMPLETED'
JOIN survey_response_detail d ON d.response_id=r.response_id AND d.question_id=q.question_id
JOIN student st ON st.student_id=r.student_id
JOIN department dpt ON dpt.department_id=st.department_id
GROUP BY s.survey_id,s.survey_name,p.program_id,p.detail_program_name,
 q.question_id,q.question_order,q.question_text,q.question_type,
 dpt.department_id,dpt.department_name,st.grade
UNION ALL
SELECT s.survey_id,s.survey_name,p.program_id,p.detail_program_name,
 q.question_id,q.question_order,q.question_text,q.question_type,
 dpt.department_id,dpt.department_name,st.grade,
 CAST(NULL AS NUMBER) average_score,1 response_count,d.answer_text
FROM satisfaction_survey s
JOIN program p ON p.program_id=s.program_id
JOIN survey_question q ON q.survey_id=s.survey_id AND q.is_active='Y' AND q.question_type='TEXT'
JOIN survey_response r ON r.survey_id=s.survey_id AND r.response_status='COMPLETED'
JOIN survey_response_detail d ON d.response_id=r.response_id AND d.question_id=q.question_id
JOIN student st ON st.student_id=r.student_id
JOIN department dpt ON dpt.department_id=st.department_id;

