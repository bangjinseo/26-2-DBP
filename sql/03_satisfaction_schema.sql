CREATE OR REPLACE PACKAGE BODY satisfaction_workflow AS
 PROCEDURE require_permission(p_actor NUMBER,p_code VARCHAR2) IS
  v_count NUMBER;
 BEGIN
  SELECT COUNT(*) INTO v_count
  FROM user_account u JOIN role_permission rp ON rp.role_id=u.role_id
  JOIN permission p ON p.permission_id=rp.permission_id
  WHERE u.user_id=p_actor AND u.is_active='Y' AND p.function_code=p_code;
  IF v_count=0 THEN RAISE_APPLICATION_ERROR(-20051,'Active user lacks required permission'); END IF;
 END;

 PROCEDURE log_change(p_actor NUMBER,p_type VARCHAR2,p_id NUMBER,p_action VARCHAR2,
                      p_old VARCHAR2,p_new VARCHAR2,p_reason VARCHAR2) IS
 BEGIN
  INSERT INTO change_log(actor_user_id,target_type,target_id,action_type,old_value,new_value,reason)
  VALUES(p_actor,p_type,p_id,p_action,p_old,p_new,p_reason);
 END;

 PROCEDURE create_survey(p_actor NUMBER,p_program NUMBER,p_name VARCHAR2,
   p_start DATE,p_end DATE,p_survey_id OUT NUMBER) IS
 BEGIN
  SAVEPOINT satisfaction_create;
  require_permission(p_actor,'SATISFACTION_MANAGE');
  IF p_name IS NULL OR p_start IS NULL OR p_end IS NULL OR p_end<p_start THEN
   RAISE_APPLICATION_ERROR(-20052,'Survey name and valid date range are required');
  END IF;
  INSERT INTO satisfaction_survey(program_id,survey_name,start_date,end_date,created_by)
   VALUES(p_program,p_name,p_start,p_end,p_actor) RETURNING survey_id INTO p_survey_id;
  log_change(p_actor,'SATISFACTION_SURVEY',p_survey_id,'CREATE',NULL,'DRAFT','Survey created');
 EXCEPTION WHEN OTHERS THEN ROLLBACK TO satisfaction_create; RAISE;
 END;

 PROCEDURE add_question(p_actor NUMBER,p_survey NUMBER,p_order NUMBER,
   p_text VARCHAR2,p_type VARCHAR2,p_required CHAR,p_question_id OUT NUMBER) IS
  v_status satisfaction_survey.survey_status%TYPE;
 BEGIN
  SAVEPOINT satisfaction_question;
  require_permission(p_actor,'SATISFACTION_MANAGE');
  SELECT survey_status INTO v_status FROM satisfaction_survey WHERE survey_id=p_survey FOR UPDATE;
  IF v_status<>'DRAFT' OR p_order IS NULL OR p_order<=0 OR TRIM(p_text) IS NULL
     OR p_type NOT IN ('SCORE','TEXT') OR p_required NOT IN ('Y','N') THEN
   RAISE_APPLICATION_ERROR(-20053,'Question can only be added to a valid draft survey');
  END IF;
  INSERT INTO survey_question(survey_id,question_order,question_text,question_type,is_required)
   VALUES(p_survey,p_order,p_text,p_type,p_required) RETURNING question_id INTO p_question_id;
  log_change(p_actor,'SURVEY_QUESTION',p_question_id,'CREATE',NULL,
    'survey='||p_survey||'; order='||p_order||'; type='||p_type,'Question created');
 EXCEPTION WHEN OTHERS THEN ROLLBACK TO satisfaction_question; RAISE;
 END;

 PROCEDURE set_survey_status(p_actor NUMBER,p_survey NUMBER,p_status VARCHAR2,p_reason VARCHAR2) IS
  v_old satisfaction_survey.survey_status%TYPE;
  v_start DATE; v_end DATE; v_count NUMBER;
 BEGIN
  SAVEPOINT satisfaction_status;
  require_permission(p_actor,'SATISFACTION_MANAGE');
  IF TRIM(p_reason) IS NULL THEN RAISE_APPLICATION_ERROR(-20054,'Reason is required'); END IF;
  SELECT survey_status,start_date,end_date INTO v_old,v_start,v_end
   FROM satisfaction_survey WHERE survey_id=p_survey FOR UPDATE;
  IF NOT ((v_old='DRAFT' AND p_status='OPEN') OR (v_old='OPEN' AND p_status='CLOSED')) THEN
   RAISE_APPLICATION_ERROR(-20055,'Invalid survey state transition');
  END IF;
  IF p_status='OPEN' THEN
   SELECT COUNT(*) INTO v_count FROM survey_question WHERE survey_id=p_survey AND is_active='Y';
   IF v_count=0 OR v_start>TRUNC(SYSDATE) OR v_end<TRUNC(SYSDATE) THEN
    RAISE_APPLICATION_ERROR(-20056,'Survey requires questions and an active date range');
   END IF;
  END IF;
  UPDATE satisfaction_survey SET survey_status=p_status WHERE survey_id=p_survey;
  log_change(p_actor,'SATISFACTION_SURVEY',p_survey,p_status,v_old,p_status,p_reason);
 EXCEPTION WHEN OTHERS THEN ROLLBACK TO satisfaction_status; RAISE;
 END;

 PROCEDURE start_response(p_actor NUMBER,p_student NUMBER,p_survey NUMBER,p_response_id OUT NUMBER) IS
  v_owner NUMBER; v_status VARCHAR2(10); v_start DATE; v_end DATE;
 BEGIN
  SAVEPOINT satisfaction_start;
  require_permission(p_actor,'SATISFACTION_RESPOND');
  SELECT user_id INTO v_owner FROM student WHERE student_id=p_student;
  IF v_owner<>p_actor THEN RAISE_APPLICATION_ERROR(-20051,'Student may respond for own account only'); END IF;
  SELECT survey_status,start_date,end_date INTO v_status,v_start,v_end
   FROM satisfaction_survey WHERE survey_id=p_survey;
  IF v_status<>'OPEN' OR TRUNC(SYSDATE)<v_start OR TRUNC(SYSDATE)>v_end THEN
   RAISE_APPLICATION_ERROR(-20057,'Survey is not currently accepting responses');
  END IF;
  INSERT INTO survey_response(survey_id,student_id) VALUES(p_survey,p_student)
   RETURNING response_id INTO p_response_id;
 EXCEPTION WHEN OTHERS THEN ROLLBACK TO satisfaction_start; RAISE;
 END;

 PROCEDURE answer_question(p_actor NUMBER,p_response NUMBER,p_question NUMBER,
   p_score NUMBER,p_text VARCHAR2) IS
  v_owner NUMBER; v_type VARCHAR2(10); v_status VARCHAR2(15); v_survey NUMBER;
 BEGIN
  SAVEPOINT satisfaction_answer;
  SELECT s.user_id,r.response_status,r.survey_id INTO v_owner,v_status,v_survey
   FROM survey_response r JOIN student s ON s.student_id=r.student_id
   WHERE r.response_id=p_response FOR UPDATE OF r.response_status;
  require_permission(p_actor,'SATISFACTION_RESPOND');
  IF v_owner<>p_actor OR v_status<>'IN_PROGRESS' THEN
   RAISE_APPLICATION_ERROR(-20051,'Only the owner may edit an in-progress response');
  END IF;
  SELECT question_type INTO v_type FROM survey_question
   WHERE question_id=p_question AND survey_id=v_survey AND is_active='Y';
  IF (v_type='SCORE' AND (p_score IS NULL OR p_score NOT BETWEEN 1 AND 5 OR p_text IS NOT NULL))
     OR (v_type='TEXT' AND (p_score IS NOT NULL OR TRIM(p_text) IS NULL)) THEN
   RAISE_APPLICATION_ERROR(-20058,'Answer does not match question type or allowed range');
  END IF;
  UPDATE survey_response_detail SET score=p_score,answer_text=p_text,answered_at=LOCALTIMESTAMP
   WHERE response_id=p_response AND question_id=p_question;
  IF SQL%ROWCOUNT=0 THEN
   INSERT INTO survey_response_detail(response_id,survey_id,question_id,score,answer_text)
    VALUES(p_response,v_survey,p_question,p_score,p_text);
  END IF;
 EXCEPTION WHEN OTHERS THEN ROLLBACK TO satisfaction_answer; RAISE;
 END;

 PROCEDURE complete_response(p_actor NUMBER,p_response NUMBER) IS
  v_owner NUMBER; v_status VARCHAR2(15); v_survey NUMBER; v_missing NUMBER;
 BEGIN
  SAVEPOINT satisfaction_complete;
  SELECT s.user_id,r.response_status,r.survey_id INTO v_owner,v_status,v_survey
   FROM survey_response r JOIN student s ON s.student_id=r.student_id
   WHERE r.response_id=p_response FOR UPDATE OF r.response_status;
  require_permission(p_actor,'SATISFACTION_RESPOND');
  IF v_owner<>p_actor OR v_status<>'IN_PROGRESS' THEN
   RAISE_APPLICATION_ERROR(-20051,'Only the owner may complete an in-progress response');
  END IF;
  SELECT COUNT(*) INTO v_missing FROM survey_question q
   WHERE q.survey_id=v_survey AND q.is_active='Y' AND q.is_required='Y'
    AND NOT EXISTS(SELECT 1 FROM survey_response_detail d
      WHERE d.response_id=p_response AND d.question_id=q.question_id);
  IF v_missing>0 THEN RAISE_APPLICATION_ERROR(-20059,'Required survey questions are unanswered'); END IF;
  UPDATE survey_response SET response_status='COMPLETED',completed_at=LOCALTIMESTAMP
   WHERE response_id=p_response;
  log_change(p_actor,'SURVEY_RESPONSE',p_response,'COMPLETE','IN_PROGRESS','COMPLETED','Survey response completed');
 EXCEPTION WHEN OTHERS THEN ROLLBACK TO satisfaction_complete; RAISE;
 END;

 PROCEDURE open_result(p_actor NUMBER,p_survey NUMBER,p_result OUT SYS_REFCURSOR) IS
 BEGIN
  require_permission(p_actor,'SATISFACTION_RESULT_READ');
  OPEN p_result FOR SELECT * FROM v_satisfaction_summary WHERE survey_id=p_survey
   ORDER BY question_order,question_id;
 END;

 PROCEDURE open_department_result(p_actor NUMBER,p_survey NUMBER,p_result OUT SYS_REFCURSOR) IS
 BEGIN
  require_permission(p_actor,'SATISFACTION_RESULT_READ');
  OPEN p_result FOR SELECT * FROM v_satisfaction_by_department WHERE survey_id=p_survey
   ORDER BY department_name,grade,question_order,answer_text;
 END;
END satisfaction_workflow;
