-- 공통 테이블은 fixtures/00_common_fixture.sql 또는 팀 공통 DDL로 먼저 생성.
CREATE TABLE mileage_standard (
 standard_id NUMBER(19) PRIMARY KEY,
 program_id NUMBER(19) NOT NULL REFERENCES program(program_id),
 participation_award_type VARCHAR2(20 CHAR) NOT NULL CHECK(participation_award_type IN ('PARTICIPATION','AWARD')),
 grant_mileage NUMBER(9) NOT NULL CHECK(grant_mileage >= 0),
 CONSTRAINT uq_mileage_standard UNIQUE(program_id,participation_award_type)
);
CREATE TABLE mileage_application (
 application_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 student_id NUMBER(19) NOT NULL REFERENCES student(student_id),
 standard_id NUMBER(19) NOT NULL REFERENCES mileage_standard(standard_id),
 applied_mileage NUMBER(9) NOT NULL CHECK(applied_mileage >= 0),
 applied_at TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
 status VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL CHECK(status IN ('PENDING','APPROVED','REJECTED','CANCELLED','REVOKED')),
 approver_id NUMBER(19) REFERENCES user_account(user_id),
 approved_at TIMESTAMP,
 memo VARCHAR2(500 CHAR),
 CONSTRAINT uq_mileage_application UNIQUE(student_id,standard_id),
 CONSTRAINT ck_mileage_approval CHECK(
 (status IN ('APPROVED','REVOKED') AND approver_id IS NOT NULL AND approved_at IS NOT NULL)
 OR (status IN ('PENDING','REJECTED','CANCELLED') AND approver_id IS NULL AND approved_at IS NULL))
);
CREATE TABLE attachment_file (
 attachment_file_id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 application_id NUMBER NOT NULL REFERENCES mileage_application(application_id),
 file_name VARCHAR2(255 CHAR) NOT NULL,
 storage_path VARCHAR2(500 CHAR) NOT NULL,
 uploaded_at TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL
);
CREATE TABLE mileage_accrual (
 accrual_id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 application_id NUMBER NOT NULL UNIQUE REFERENCES mileage_application(application_id),
 earned_mileage NUMBER(9) NOT NULL CHECK(earned_mileage >= 0),
 earned_at TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
 status VARCHAR2(10 CHAR) DEFAULT 'ACTIVE' NOT NULL CHECK(status IN ('ACTIVE','REVOKED'))
);
CREATE TABLE mileage_process_history (
 process_history_id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 application_id NUMBER NOT NULL REFERENCES mileage_application(application_id),
 old_status VARCHAR2(20 CHAR) NOT NULL CHECK(old_status IN ('PENDING','APPROVED','REJECTED','CANCELLED','REVOKED')),
 process_status VARCHAR2(20 CHAR) NOT NULL CHECK(process_status IN ('APPROVED','REJECTED','CANCELLED','REVOKED')),
 processor_id NUMBER(19) NOT NULL REFERENCES user_account(user_id),
 processed_at TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
 process_comment VARCHAR2(500 CHAR) NOT NULL
);
CREATE TABLE budget_project (
 project_id NUMBER(19) PRIMARY KEY,
 business_year NUMBER(4) NOT NULL,
 business_round NUMBER(4) NOT NULL CHECK(business_round > 0),
 project_name VARCHAR2(100 CHAR) NOT NULL,
 start_date DATE NOT NULL,
 end_date DATE NOT NULL,
 status VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL CHECK(status IN ('ACTIVE','CLOSED')),
 CHECK(end_date >= start_date)
);
CREATE TABLE budget_item (
 budget_item_id NUMBER(19) PRIMARY KEY,
 item_code VARCHAR2(30 CHAR) NOT NULL UNIQUE,
 item_name VARCHAR2(100 CHAR) NOT NULL UNIQUE,
 is_active CHAR(1) DEFAULT 'Y' NOT NULL CHECK(is_active IN ('Y','N'))
);
CREATE TABLE project_budget (
 project_budget_id NUMBER(19) PRIMARY KEY,
 project_id NUMBER(19) NOT NULL REFERENCES budget_project(project_id),
 budget_item_id NUMBER(19) NOT NULL REFERENCES budget_item(budget_item_id),
 initial_amount NUMBER(15,2) NOT NULL CHECK(initial_amount >= 0),
 current_amount NUMBER(15,2) NOT NULL CHECK(current_amount >= 0),
 spending_limit NUMBER(15,2) NOT NULL CHECK(spending_limit >= 0),
 status VARCHAR2(20 CHAR) DEFAULT 'CONFIRMED' NOT NULL CHECK(status IN ('DRAFT','CONFIRMED','CLOSED')),
 input_user_id NUMBER(19) NOT NULL REFERENCES user_account(user_id),
 input_at TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
 CONSTRAINT uq_project_budget UNIQUE(project_id,budget_item_id),
 CHECK(spending_limit <= current_amount)
);
CREATE TABLE expense_subject (
 expense_subject_id NUMBER(19) PRIMARY KEY,
 subject_name VARCHAR2(100 CHAR) NOT NULL UNIQUE,
 is_active CHAR(1) DEFAULT 'Y' NOT NULL CHECK(is_active IN ('Y','N'))
);
CREATE TABLE expense (
 expense_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 project_budget_id NUMBER(19) NOT NULL REFERENCES project_budget(project_budget_id),
 professor_id NUMBER(19) NOT NULL REFERENCES professor(professor_id),
 expense_subject_id NUMBER(19) NOT NULL REFERENCES expense_subject(expense_subject_id),
 input_user_id NUMBER(19) NOT NULL REFERENCES user_account(user_id),
 expense_date DATE NOT NULL,
 detail_item VARCHAR2(200 CHAR) NOT NULL,
 expense_amount NUMBER(15,2) NOT NULL CHECK(expense_amount > 0),
 status VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL CHECK(status IN ('PENDING','APPROVED','REJECTED','CANCELLED')),
 processor_id NUMBER(19) REFERENCES user_account(user_id),
 processed_at TIMESTAMP,
 CHECK((status='PENDING' AND processor_id IS NULL AND processed_at IS NULL)
 OR (status <> 'PENDING' AND processor_id IS NOT NULL AND processed_at IS NOT NULL))
);
CREATE TABLE expense_process_history (
 history_id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 expense_id NUMBER NOT NULL REFERENCES expense(expense_id),
 old_status VARCHAR2(20 CHAR) NOT NULL CHECK(old_status IN ('PENDING','APPROVED','REJECTED','CANCELLED')),
 process_status VARCHAR2(20 CHAR) NOT NULL CHECK(process_status IN ('APPROVED','REJECTED','CANCELLED')),
 processor_id NUMBER(19) NOT NULL REFERENCES user_account(user_id),
 processed_at TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
 reason VARCHAR2(500 CHAR) NOT NULL
);
CREATE TABLE budget_change_history (
 change_history_id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 project_budget_id NUMBER(19) NOT NULL REFERENCES project_budget(project_budget_id),
 changer_id NUMBER(19) NOT NULL REFERENCES user_account(user_id),
 old_amount NUMBER(15,2) NOT NULL,
 new_amount NUMBER(15,2) NOT NULL,
 old_limit NUMBER(15,2) NOT NULL,
 new_limit NUMBER(15,2) NOT NULL,
 changed_at TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
 reason VARCHAR2(500 CHAR) NOT NULL
);
-- 승인 시 합계 조회와 FK 조회에 사용하는 인덱스.
CREATE INDEX ix_expense_budget_status ON expense(project_budget_id,status);
CREATE INDEX ix_mileage_standard ON mileage_application(standard_id);
CREATE INDEX ix_attachment_application ON attachment_file(application_id);
CREATE INDEX ix_mileage_history ON mileage_process_history(application_id);
CREATE INDEX ix_expense_history ON expense_process_history(expense_id);
CREATE INDEX ix_budget_history ON budget_change_history(project_budget_id);

CREATE OR REPLACE VIEW v_student_mileage AS
SELECT s.student_id,s.student_name,NVL(m.total_mileage,0) total_mileage
FROM student s LEFT JOIN (
 SELECT a.student_id,SUM(c.earned_mileage) total_mileage
 FROM mileage_application a JOIN mileage_accrual c ON c.application_id=a.application_id
 WHERE a.status='APPROVED' AND c.status='ACTIVE' GROUP BY a.student_id
) m ON m.student_id=s.student_id;

CREATE OR REPLACE VIEW v_budget_summary AS
SELECT p.project_id,p.project_budget_id,i.item_code,i.item_name,
 p.initial_amount,p.current_amount,p.spending_limit,
 NVL(e.approved_expense,0) approved_expense,
 p.current_amount-NVL(e.approved_expense,0) balance,
 p.spending_limit-NVL(e.approved_expense,0) available_limit,
 CASE WHEN p.current_amount=0 THEN 0 ELSE ROUND(NVL(e.approved_expense,0)/p.current_amount*100,2) END execution_rate
FROM project_budget p JOIN budget_item i ON i.budget_item_id=p.budget_item_id
LEFT JOIN (SELECT project_budget_id,SUM(expense_amount) approved_expense
 FROM expense WHERE status='APPROVED' GROUP BY project_budget_id) e
 ON e.project_budget_id=p.project_budget_id;

CREATE OR REPLACE PACKAGE pbl_workflow AS
 PROCEDURE submit_mileage(p_actor NUMBER,p_student NUMBER,p_standard NUMBER,p_id OUT NUMBER);
 PROCEDURE process_mileage(p_actor NUMBER,p_id NUMBER,p_action VARCHAR2,p_reason VARCHAR2);
 PROCEDURE submit_expense(p_actor NUMBER,p_budget NUMBER,p_professor NUMBER,p_subject NUMBER,
   p_date DATE,p_detail VARCHAR2,p_amount NUMBER,p_id OUT NUMBER);
 PROCEDURE process_expense(p_actor NUMBER,p_id NUMBER,p_action VARCHAR2,p_reason VARCHAR2);
 PROCEDURE change_budget(p_actor NUMBER,p_budget NUMBER,p_amount NUMBER,p_limit NUMBER,p_reason VARCHAR2);
END pbl_workflow;
/
CREATE OR REPLACE PACKAGE BODY pbl_workflow AS
 PROCEDURE require_role(p_actor NUMBER,p_master BOOLEAN) IS v_role user_account.user_type%TYPE;
 BEGIN
  SELECT user_type INTO v_role FROM user_account WHERE user_id=p_actor AND is_active='Y';
  IF (p_master AND v_role <> 'MASTER') OR (NOT p_master AND v_role NOT IN ('ADMIN','MASTER')) THEN
   RAISE_APPLICATION_ERROR(-20001,'Role not authorized');
  END IF;
 EXCEPTION WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20001,'Active actor required');
 END;
 PROCEDURE log_change(p_actor NUMBER,p_type VARCHAR2,p_id NUMBER,p_action VARCHAR2,
 p_old VARCHAR2,p_new VARCHAR2,p_reason VARCHAR2) IS
 BEGIN
  INSERT INTO change_log(actor_user_id,target_type,target_id,action_type,old_value,new_value,reason)
  VALUES(p_actor,p_type,p_id,p_action,p_old,p_new,p_reason);
 END;
 PROCEDURE require_reason(p_reason VARCHAR2) IS
 BEGIN
  IF TRIM(p_reason) IS NULL THEN RAISE_APPLICATION_ERROR(-20004,'Reason is required'); END IF;
 END;
 PROCEDURE submit_mileage(p_actor NUMBER,p_student NUMBER,p_standard NUMBER,p_id OUT NUMBER) IS
  v_owner NUMBER; v_points NUMBER;
 BEGIN
  SAVEPOINT mileage_submit;
  SELECT s.user_id INTO v_owner FROM student s JOIN user_account u ON u.user_id=s.user_id
   WHERE s.student_id=p_student AND u.is_active='Y' AND u.user_type='STUDENT';
  IF p_actor IS NULL OR p_actor<>v_owner THEN RAISE_APPLICATION_ERROR(-20001,'Student may submit own application only'); END IF;
  SELECT grant_mileage INTO v_points FROM mileage_standard WHERE standard_id=p_standard;
  INSERT INTO mileage_application(student_id,standard_id,applied_mileage)
   VALUES(p_student,p_standard,v_points) RETURNING application_id INTO p_id;
  log_change(p_actor,'MILEAGE',p_id,'SUBMIT',NULL,'PENDING','Student submission');
 EXCEPTION WHEN OTHERS THEN ROLLBACK TO mileage_submit; RAISE;
 END;
 PROCEDURE process_mileage(p_actor NUMBER,p_id NUMBER,p_action VARCHAR2,p_reason VARCHAR2) IS
  v_old mileage_application.status%TYPE; v_points NUMBER; v_owner NUMBER;
 BEGIN
  SAVEPOINT mileage_process;
  require_reason(p_reason);
  SELECT a.status,a.applied_mileage,s.user_id INTO v_old,v_points,v_owner
   FROM mileage_application a JOIN student s ON s.student_id=a.student_id
   WHERE a.application_id=p_id FOR UPDATE OF a.status;
  IF p_action='CANCELLED' THEN
   IF p_actor IS NULL OR p_actor<>v_owner THEN require_role(p_actor,TRUE); END IF;
  ELSE require_role(p_actor,TRUE); END IF;
  IF p_action IS NULL OR NOT ((v_old='PENDING' AND p_action IN ('APPROVED','REJECTED','CANCELLED'))
   OR (v_old='APPROVED' AND p_action='REVOKED')) THEN
   RAISE_APPLICATION_ERROR(-20002,'Invalid mileage state transition');
  END IF;
  UPDATE mileage_application SET status=p_action,
   approver_id=CASE WHEN p_action='APPROVED' THEN p_actor ELSE approver_id END,
   approved_at=CASE WHEN p_action='APPROVED' THEN LOCALTIMESTAMP ELSE approved_at END
   WHERE application_id=p_id;
  IF p_action='APPROVED' THEN
   INSERT INTO mileage_accrual(application_id,earned_mileage) VALUES(p_id,v_points);
  ELSIF p_action='REVOKED' THEN
   UPDATE mileage_accrual SET status='REVOKED' WHERE application_id=p_id AND status='ACTIVE';
   IF SQL%ROWCOUNT<>1 THEN RAISE_APPLICATION_ERROR(-20005,'Accrual inconsistency'); END IF;
  END IF;
  INSERT INTO mileage_process_history(application_id,old_status,process_status,processor_id,process_comment)
   VALUES(p_id,v_old,p_action,p_actor,p_reason);
  log_change(p_actor,'MILEAGE',p_id,p_action,v_old,p_action,p_reason);
 EXCEPTION WHEN OTHERS THEN ROLLBACK TO mileage_process; RAISE;
 END;
 PROCEDURE submit_expense(p_actor NUMBER,p_budget NUMBER,p_professor NUMBER,p_subject NUMBER,
   p_date DATE,p_detail VARCHAR2,p_amount NUMBER,p_id OUT NUMBER) IS v_budget NUMBER;
 BEGIN
  SAVEPOINT expense_submit;
  require_role(p_actor,FALSE);
  SELECT b.project_budget_id INTO v_budget FROM project_budget b JOIN budget_project p ON p.project_id=b.project_id
   JOIN budget_item i ON i.budget_item_id=b.budget_item_id
   WHERE b.project_budget_id=p_budget AND b.status='CONFIRMED' AND p.status='ACTIVE' AND i.is_active='Y';
  INSERT INTO expense(project_budget_id,professor_id,expense_subject_id,input_user_id,expense_date,detail_item,expense_amount)
   VALUES(p_budget,p_professor,p_subject,p_actor,p_date,p_detail,p_amount) RETURNING expense_id INTO p_id;
  log_change(p_actor,'EXPENSE',p_id,'SUBMIT',NULL,'PENDING','Expense submission');
 EXCEPTION WHEN OTHERS THEN ROLLBACK TO expense_submit; RAISE;
 END;
 PROCEDURE process_expense(p_actor NUMBER,p_id NUMBER,p_action VARCHAR2,p_reason VARCHAR2) IS
  v_budget NUMBER; v_old expense.status%TYPE; v_amount NUMBER; v_limit NUMBER; v_total NUMBER; v_status project_budget.status%TYPE;
 BEGIN
  SAVEPOINT expense_process;
  require_role(p_actor,TRUE); require_reason(p_reason);
  SELECT project_budget_id INTO v_budget FROM expense WHERE expense_id=p_id;
  -- 같은 사업예산 행을 잠근 뒤 승인 합계를 계산. 예산 변경도 동일한 잠금을 사용한다.
  SELECT spending_limit,status INTO v_limit,v_status FROM project_budget WHERE project_budget_id=v_budget FOR UPDATE;
  SELECT status,expense_amount INTO v_old,v_amount FROM expense WHERE expense_id=p_id FOR UPDATE;
  IF p_action IS NULL OR NOT ((v_old='PENDING' AND p_action IN ('APPROVED','REJECTED','CANCELLED'))
   OR (v_old='APPROVED' AND p_action='CANCELLED')) THEN
   RAISE_APPLICATION_ERROR(-20002,'Invalid expense state transition');
  END IF;
  IF p_action='APPROVED' THEN
   IF v_status<>'CONFIRMED' THEN RAISE_APPLICATION_ERROR(-20006,'Budget must be confirmed'); END IF;
   SELECT NVL(SUM(expense_amount),0) INTO v_total FROM expense WHERE project_budget_id=v_budget AND status='APPROVED';
   IF v_total+v_amount>v_limit THEN RAISE_APPLICATION_ERROR(-20003,'Spending limit exceeded'); END IF;
  END IF;
  UPDATE expense SET status=p_action,processor_id=p_actor,processed_at=LOCALTIMESTAMP WHERE expense_id=p_id;
  INSERT INTO expense_process_history(expense_id,old_status,process_status,processor_id,reason)
   VALUES(p_id,v_old,p_action,p_actor,p_reason);
  log_change(p_actor,'EXPENSE',p_id,p_action,v_old,p_action,p_reason);
 EXCEPTION WHEN OTHERS THEN ROLLBACK TO expense_process; RAISE;
 END;
 PROCEDURE change_budget(p_actor NUMBER,p_budget NUMBER,p_amount NUMBER,p_limit NUMBER,p_reason VARCHAR2) IS
  v_old_amount NUMBER; v_old_limit NUMBER; v_total NUMBER;
 BEGIN
  SAVEPOINT budget_change;
  require_role(p_actor,TRUE); require_reason(p_reason);
  SELECT current_amount,spending_limit INTO v_old_amount,v_old_limit FROM project_budget WHERE project_budget_id=p_budget FOR UPDATE;
  IF p_amount IS NULL OR p_limit IS NULL OR p_amount<0 OR p_limit<0 OR p_limit>p_amount THEN
   RAISE_APPLICATION_ERROR(-20007,'Invalid budget amount or limit');
  END IF;
  SELECT NVL(SUM(expense_amount),0) INTO v_total FROM expense WHERE project_budget_id=p_budget AND status='APPROVED';
  IF p_limit<v_total THEN RAISE_APPLICATION_ERROR(-20003,'New limit below approved expense'); END IF;
  UPDATE project_budget SET current_amount=p_amount,spending_limit=p_limit WHERE project_budget_id=p_budget;
  INSERT INTO budget_change_history(project_budget_id,changer_id,old_amount,new_amount,old_limit,new_limit,reason)
   VALUES(p_budget,p_actor,v_old_amount,p_amount,v_old_limit,p_limit,p_reason);
  log_change(p_actor,'BUDGET',p_budget,'UPDATE',v_old_amount||' / '||v_old_limit,p_amount||' / '||p_limit,p_reason);
 EXCEPTION WHEN OTHERS THEN ROLLBACK TO budget_change; RAISE;
 END;
END pbl_workflow;
/
