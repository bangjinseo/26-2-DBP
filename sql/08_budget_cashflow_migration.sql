-- 예산 수입·실제 지급 관리 확장 마이그레이션.
-- 기존 EXPENSE 승인 집계는 변경하지 않으며, 이 파일은 스키마당 한 번만 실행한다.

ALTER TABLE expense ADD (
 payment_status VARCHAR2(20 CHAR) DEFAULT 'UNTRACKED' NOT NULL,
 paid_at TIMESTAMP,
 paid_by NUMBER(19),
 payment_reference VARCHAR2(100 CHAR)
);

ALTER TABLE expense ADD CONSTRAINT ck_expense_payment_status
 CHECK(payment_status IN ('UNTRACKED','UNPAID','PAID'));

ALTER TABLE expense ADD CONSTRAINT ck_expense_payment_meta
 CHECK(
  (payment_status IN ('UNTRACKED','UNPAID') AND paid_at IS NULL AND paid_by IS NULL)
  OR (payment_status='PAID' AND paid_at IS NOT NULL AND paid_by IS NOT NULL)
 );

ALTER TABLE expense ADD CONSTRAINT fk_expense_paid_by
 FOREIGN KEY(paid_by) REFERENCES user_account(user_id);

CREATE TABLE income (
 income_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 project_budget_id NUMBER(19) NOT NULL REFERENCES project_budget(project_budget_id),
 income_date DATE NOT NULL,
 income_amount NUMBER(15,2) NOT NULL CHECK(income_amount > 0),
 income_type VARCHAR2(50 CHAR) NOT NULL,
 income_description VARCHAR2(500 CHAR) NOT NULL,
 manager_id NUMBER(19) NOT NULL REFERENCES user_account(user_id),
 status VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL
  CHECK(status IN ('PENDING','RECEIVED','REJECTED','CANCELLED')),
 processor_id NUMBER(19) REFERENCES user_account(user_id),
 processed_at TIMESTAMP,
 created_at TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
 CONSTRAINT ck_income_processing CHECK(
  (status='PENDING' AND processor_id IS NULL AND processed_at IS NULL)
  OR (status<>'PENDING' AND processor_id IS NOT NULL AND processed_at IS NOT NULL)
 )
);

CREATE INDEX ix_income_budget_status ON income(project_budget_id,status,income_date);
CREATE INDEX ix_expense_payment_status ON expense(project_budget_id,payment_status,expense_date);

CREATE OR REPLACE VIEW v_budget_cash_summary AS
SELECT pb.project_id,
       pb.project_budget_id,
       bi.item_code,
       bi.item_name,
       pb.current_amount,
       NVL(ex.approved_expense,0) approved_expense,
       pb.current_amount-NVL(ex.approved_expense,0) budget_balance,
       NVL(ex.pending_expense_count,0) pending_expense_count,
       CASE WHEN pb.current_amount=0 THEN NULL
            ELSE ROUND(NVL(ex.approved_expense,0)/pb.current_amount*100,2)
       END execution_rate,
       CASE WHEN NVL(inc.income_data_count,0)=0 THEN NULL
            ELSE NVL(inc.total_income,0)
       END total_income,
       CASE WHEN NVL(ex.payment_data_count,0)=0 THEN NULL
            ELSE NVL(ex.actual_paid,0)
       END actual_paid,
       CASE WHEN NVL(inc.income_data_count,0)=0 OR NVL(ex.payment_data_count,0)=0 THEN NULL
            ELSE NVL(inc.total_income,0)-NVL(ex.actual_paid,0)
       END actual_cash_balance,
       NVL(inc.income_data_count,0) income_data_count,
       NVL(ex.payment_data_count,0) payment_data_count
FROM project_budget pb
JOIN budget_item bi ON bi.budget_item_id=pb.budget_item_id
LEFT JOIN (
 SELECT project_budget_id,
        SUM(CASE WHEN status='APPROVED' THEN expense_amount ELSE 0 END) approved_expense,
        SUM(CASE WHEN status='PENDING' THEN 1 ELSE 0 END) pending_expense_count,
        SUM(CASE WHEN payment_status='PAID' THEN expense_amount ELSE 0 END) actual_paid,
        SUM(CASE WHEN payment_status IN ('UNPAID','PAID') THEN 1 ELSE 0 END) payment_data_count
 FROM expense
 GROUP BY project_budget_id
) ex ON ex.project_budget_id=pb.project_budget_id
LEFT JOIN (
 SELECT project_budget_id,
        SUM(CASE WHEN status='RECEIVED' THEN income_amount ELSE 0 END) total_income,
        COUNT(*) income_data_count
 FROM income
 GROUP BY project_budget_id
) inc ON inc.project_budget_id=pb.project_budget_id;

CREATE OR REPLACE VIEW v_budget_transaction AS
SELECT 'INC-'||TO_CHAR(i.income_id) transaction_id,
       i.project_budget_id,
       i.income_date transaction_date,
       'INCOME' transaction_type,
       i.income_type detail_item,
       u.login_id manager_name,
       i.income_description transaction_description,
       i.income_amount income_amount,
       CAST(NULL AS NUMBER(15,2)) expense_amount,
       i.status approval_status,
       CASE WHEN i.status='RECEIVED' THEN 'RECEIVED' END payment_status
FROM income i
JOIN user_account u ON u.user_id=i.manager_id
UNION ALL
SELECT 'EXP-'||TO_CHAR(e.expense_id) transaction_id,
       e.project_budget_id,
       e.expense_date transaction_date,
       'EXPENSE' transaction_type,
       es.subject_name detail_item,
       p.name manager_name,
       e.detail_item transaction_description,
       CAST(NULL AS NUMBER(15,2)) income_amount,
       e.expense_amount expense_amount,
       e.status approval_status,
       e.payment_status payment_status
FROM expense e
JOIN expense_subject es ON es.expense_subject_id=e.expense_subject_id
JOIN professor p ON p.professor_id=e.professor_id;

CREATE OR REPLACE PACKAGE budget_cashflow_workflow AS
 PROCEDURE register_income(
  p_actor NUMBER,p_budget NUMBER,p_date DATE,p_amount NUMBER,
  p_type VARCHAR2,p_description VARCHAR2,p_id OUT NUMBER);
 PROCEDURE process_income(
  p_actor NUMBER,p_id NUMBER,p_action VARCHAR2,p_reason VARCHAR2);
 PROCEDURE update_expense_payment(
  p_actor NUMBER,p_expense NUMBER,p_payment_status VARCHAR2,
  p_reference VARCHAR2,p_reason VARCHAR2);
END budget_cashflow_workflow;
/

CREATE OR REPLACE PACKAGE BODY budget_cashflow_workflow AS
 PROCEDURE require_permission(p_actor NUMBER,p_code VARCHAR2) IS v_count NUMBER;
 BEGIN
  SELECT COUNT(*) INTO v_count
  FROM user_account u
  JOIN role r ON r.role_id=u.role_id AND r.is_active='Y'
  JOIN role_permission rp ON rp.role_id=u.role_id
  JOIN permission p ON p.permission_id=rp.permission_id AND p.function_code=p_code
  WHERE u.user_id=p_actor AND u.is_active='Y';
  IF v_count=0 THEN
   RAISE_APPLICATION_ERROR(-20001,'Active user lacks required permission');
  END IF;
 END;

 PROCEDURE require_reason(p_reason VARCHAR2) IS
 BEGIN
  IF TRIM(p_reason) IS NULL THEN
   RAISE_APPLICATION_ERROR(-20004,'Reason is required');
  END IF;
 END;

 PROCEDURE log_change(
  p_actor NUMBER,p_type VARCHAR2,p_id NUMBER,p_action VARCHAR2,
  p_old VARCHAR2,p_new VARCHAR2,p_reason VARCHAR2) IS
 BEGIN
  INSERT INTO change_log(
   actor_user_id,target_type,target_id,action_type,old_value,new_value,reason
  ) VALUES(p_actor,p_type,p_id,p_action,p_old,p_new,p_reason);
 END;

 PROCEDURE register_income(
  p_actor NUMBER,p_budget NUMBER,p_date DATE,p_amount NUMBER,
  p_type VARCHAR2,p_description VARCHAR2,p_id OUT NUMBER) IS
  v_budget NUMBER;
 BEGIN
  SAVEPOINT income_register;
  require_permission(p_actor,'BUDGET_MANAGE');
  SELECT pb.project_budget_id INTO v_budget
  FROM project_budget pb
  JOIN budget_project bp ON bp.project_id=pb.project_id
  WHERE pb.project_budget_id=p_budget
    AND pb.status='CONFIRMED'
    AND bp.status='ACTIVE';
  IF p_date IS NULL OR p_amount IS NULL OR p_amount<=0
     OR TRIM(p_type) IS NULL OR TRIM(p_description) IS NULL THEN
   RAISE_APPLICATION_ERROR(-20007,'Invalid income data');
  END IF;
  INSERT INTO income(
   project_budget_id,income_date,income_amount,income_type,income_description,manager_id
  ) VALUES(p_budget,p_date,p_amount,TRIM(p_type),TRIM(p_description),p_actor)
  RETURNING income_id INTO p_id;
  log_change(p_actor,'INCOME',p_id,'SUBMIT',NULL,'PENDING','Income registration');
 EXCEPTION WHEN OTHERS THEN ROLLBACK TO income_register; RAISE;
 END;

 PROCEDURE process_income(
  p_actor NUMBER,p_id NUMBER,p_action VARCHAR2,p_reason VARCHAR2) IS
  v_old income.status%TYPE;
 BEGIN
  SAVEPOINT income_process;
  require_permission(p_actor,'BUDGET_MANAGE');
  require_reason(p_reason);
  SELECT status INTO v_old FROM income WHERE income_id=p_id FOR UPDATE;
  IF v_old<>'PENDING'
     OR p_action IS NULL
     OR p_action NOT IN ('RECEIVED','REJECTED','CANCELLED') THEN
   RAISE_APPLICATION_ERROR(-20002,'Invalid income state transition');
  END IF;
  UPDATE income
  SET status=p_action,processor_id=p_actor,processed_at=LOCALTIMESTAMP
  WHERE income_id=p_id;
  log_change(p_actor,'INCOME',p_id,p_action,v_old,p_action,p_reason);
 EXCEPTION WHEN OTHERS THEN ROLLBACK TO income_process; RAISE;
 END;

 PROCEDURE update_expense_payment(
  p_actor NUMBER,p_expense NUMBER,p_payment_status VARCHAR2,
  p_reference VARCHAR2,p_reason VARCHAR2) IS
  v_old expense.payment_status%TYPE;
  v_approval expense.status%TYPE;
 BEGIN
  SAVEPOINT expense_payment;
  require_permission(p_actor,'EXPENSE_PROCESS');
  require_reason(p_reason);
  SELECT payment_status,status INTO v_old,v_approval
  FROM expense WHERE expense_id=p_expense FOR UPDATE;
  IF v_approval<>'APPROVED' THEN
   RAISE_APPLICATION_ERROR(-20002,'Only approved expense can be paid');
  END IF;
  IF p_payment_status IS NULL
     OR p_payment_status NOT IN ('UNPAID','PAID')
     OR (v_old='PAID' AND p_payment_status<>v_old)
     OR v_old=p_payment_status THEN
   RAISE_APPLICATION_ERROR(-20002,'Invalid payment state transition');
  END IF;
  UPDATE expense
  SET payment_status=p_payment_status,
      paid_at=CASE WHEN p_payment_status='PAID' THEN LOCALTIMESTAMP END,
      paid_by=CASE WHEN p_payment_status='PAID' THEN p_actor END,
      payment_reference=CASE WHEN p_payment_status='PAID' THEN NULLIF(TRIM(p_reference),'') END
  WHERE expense_id=p_expense;
  log_change(
   p_actor,'EXPENSE_PAYMENT',p_expense,p_payment_status,v_old,p_payment_status,p_reason
  );
 EXCEPTION WHEN OTHERS THEN ROLLBACK TO expense_payment; RAISE;
 END;
END budget_cashflow_workflow;
/

COMMENT ON TABLE income IS '사업예산 항목별 실제 수입 등록 및 입금 처리 상태';
COMMENT ON VIEW v_budget_cash_summary IS '예산 잔액과 실제 자금 잔액을 분리한 항목별 요약';
COMMENT ON VIEW v_budget_transaction IS '수입과 지출을 동일 컬럼으로 조회하는 통합 거래내역';

